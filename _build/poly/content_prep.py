def _mn(v):
    return ('−%s' % -v) if v < 0 else str(v)

def _gt(f, label, xr=(-4, 3), yr=(-8, 8)):
    """תמונה קטנה סטטית של גרף (אותה נראות כמו בשאר האתר)"""
    W, H, ML, MT, PW, PH = 230, 190, 26, 10, 190, 160
    sx = lambda x: ML + (x - xr[0]) / (xr[1] - xr[0]) * PW
    sy = lambda y: MT + (yr[1] - y) / (yr[1] - yr[0]) * PH
    g = ''
    for i in range(int(xr[0]), int(xr[1]) + 1):
        g += '<line x1="%.1f" y1="%d" x2="%.1f" y2="%d" class="svg-grid"/>' % (sx(i), MT, sx(i), MT + PH)
    for j in range(int(yr[0]), int(yr[1]) + 1, 2):
        g += '<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" class="svg-grid"/>' % (ML, sy(j), ML + PW, sy(j))
    g += '<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" class="svg-axis"/><line x1="%.1f" y1="%d" x2="%.1f" y2="%d" class="svg-axis"/>' % (ML, sy(0), ML + PW, sy(0), sx(0), MT, sx(0), MT + PH)
    for i in range(int(xr[0]), int(xr[1]) + 1):
        if i != 0:
            g += '<text x="%.1f" y="%.1f" class="svg-num" text-anchor="middle">%s</text>' % (sx(i), sy(0) + 14, _mn(i))
    d = ''
    for k in range(0, 261):
        x = xr[0] + (xr[1] - xr[0]) * k / 260
        y = f(x)
        d += ('L' if d else 'M') + '%.1f %.1f' % (sx(x), sy(max(yr[0] - 6, min(yr[1] + 6, y))))
    cid = 'pt%d' % (sum(ord(ch) * (i + 3) for i, ch in enumerate(label)) % 99991)
    return ('<svg viewBox="0 0 %d %d" class="plot mt-svg" role="img" aria-label="%s"><defs><clipPath id="%s"><rect x="%d" y="%d" width="%d" height="%d"/></clipPath></defs>%s'
            '<path d="%s" class="svg-line svg-curve l0" clip-path="url(#%s)"/></svg>') % (W, H, label, cid, ML, MT, PW, PH, g, d, cid)

def _pth(curves, label):
    """תמונה קטנה לבחירת גרף בניחוש"""
    def path(fn):
        pts = []
        for k in range(61):
            x = -1.2 + 2.4 * k / 60
            y = max(-1.3, min(1.3, fn(x)))
            pts.append('%.1f,%.1f' % (60 + x * 46, 45 - y * 34))
        return 'M' + ' L'.join(pts)
    g = '<line x1="6" y1="45" x2="114" y2="45" stroke="#64748b" stroke-width="1.2"/><line x1="60" y1="4" x2="60" y2="86" stroke="#64748b" stroke-width="1.2"/>'
    for col, fn in curves:
        g += '<path d="%s" fill="none" stroke="%s" stroke-width="2.6"/>' % (path(fn), col)
    return '<svg viewBox="0 0 120 90" width="120" height="90" role="img" aria-label="%s">%s</svg>' % (label, g)

