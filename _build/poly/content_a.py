def FG(xr, yr, curves, caption=None, **kw):
    mys = kw.pop('mystery', None)
    spec = {'xr': xr, 'yr': yr, 'curves': curves}
    spec.update(kw)
    if mys is not None:
        # "mystery function": formula and sliders are hidden, so every value must be collected from the table, the graph or by calculation
        for k, P in spec['params'].items():
            P['hidden'] = True
            if k in mys:
                P['val'] = mys[k]
        spec['readout'] = [dict(r, rows=[dict(x, name=('g(x)' if x.get('i') == 1 and len(r['rows']) > 1 else 'f(x)')) for x in r['rows']]) for r in spec.get('readout', []) if r['k'] == 'tbl']
        for d in spec.get('drags', []):
            if d.get('lock'):
                d['fixed'] = True
        caption = 'גררו את הנקודה לאורך הגרף; שיעוריה מוצגים לידה.'
        spec['curves'] = [dict(c, name='g') if c.get('name') == 'x^n' else c for c in curves]
    return fig(spec, caption=caption)

def FREE(id, curve, pos='tr', **k):
    """continuous draggable point on a curve, live (x ; y) label attached"""
    d = {'id': id, 'x': 1.5, 'y': 0, 'onc': curve, 'coords': True, 'pos': pos}
    d.update(k)
    return d

def PAR(**kw):
    """params helper: PAR(n=(1,8,1,2)) -> {'n': {min,max,step,val,label}}"""
    return {k: {'min': v[0], 'max': v[1], 'step': v[2], 'val': v[3], 'label': (v[4] if len(v) > 4 else k)} for k, v in kw.items()}

