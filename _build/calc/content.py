c.text(r'''
**שאלות לחקירה** (נסו, ורשמו מסקנה):

1. קבעו $\Delta x=1$ ושנו את $m$. מה הקשר בין $m$ לבין $\Delta y$?
2. קבעו $m=2$ והגדילו את $\Delta x$ ל-$2$, ל-$3$, ל-$4$. מה קורה ל-$\Delta y$? נסחו כלל.
3. גררו את $Q$ למקום אחר על הישר ושמרו על אותם $m$ ו-$\Delta x$. האם $\Delta y$ משתנה? מה זה אומר על קצב השינוי?
4. שנו את $b$. האם $\Delta y$ משתנה? מה $b$ משנה בישר?
5. קבעו $\Delta x=-2$ ובדקו מה הסימן של $\Delta y$ כש-$m>0$ וכש-$m<0$.
6. מצאו ערך של $m$ שבו $\Delta y=0$ לכל $\Delta x$. איך נראה הישר?

**מה גילינו:** $\Delta y=m\cdot\Delta x$ לא תלוי במקום שבו מתחילים ולא ב-$b$, אלא רק ב-$m$ וב-$\Delta x$. לכן $m=\dfrac{\Delta y}{\Delta x}$.

| שיפוע | סוג הפונקציה | הגרף |
|---|---|---|
| $m>0$ | עולה | עולה משמאל לימין |
| $m<0$ | יורדת | יורד משמאל לימין |
| $m=0$ | קבועה | ישר מקביל לציר ה-$x$ (או מתלכד איתו) |

ככל ש-$|m|$ גדול יותר, הישר **תלול** יותר.

<p class="warn"><strong>ישר אנכי אינו פונקציה.</strong> הישר $x=4$ מקביל לציר ה-$y$, ולערך $x=4$ מתאימים אינסוף ערכי $y$. פונקציה נותנת לכל $x$ ערך אחד בלבד. לישר כזה אין שיפוע, ולכן אי אפשר לכתוב אותו בצורה $f(x)=mx+b$.</p>
''')
c.add(ex('1.E2', 'example', r'''
נתונה $f(x)=-3x+10$. כש-$x$ גדל מ-$2$ ל-$5$, כמה משתנה $f(x)$?

$\Delta x=5-2=3$ ו-$m=-3$, לכן $\Delta y=m\cdot\Delta x=-3\cdot3=-9$.

**בדיקה:** $f(2)=-3\cdot2+10=4$ ו-$f(5)=-3\cdot5+10=-5$. ואכן $-5-4=-9$.

**מסקנה:** כשהשיפוע שלילי, הערך קטן כש-$x$ גדל.
'''))
assert -3*5+10 - (-3*2+10) == -9

